def main():
    scratch_path = BASE_DIR / "scratch_categories.json"
    with open(scratch_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    altium_cats = data["altium_categories"]
    primary_cats = data["jlcparts_categories"]
    all_subcats = set()
    for sublist in data["jlcparts_hierarchy"].values():
        all_subcats.update(sublist)

    print(f"Altium in DB: {len(altium_cats)}")
    print(f"Primary in DB: {len(primary_cats)}")
    print(f"Subcategories in DB: {len(all_subcats)}")

    # Check Altium coverage
    missing_altium = set(altium_cats) - set(ALTIUM_ZH.keys())
    assert not missing_altium, f"Missing Altium categories: {missing_altium}"

    # Check Primary coverage
    missing_primary = set(primary_cats) - set(PRIMARY_ZH.keys())
    assert not missing_primary, f"Missing Primary categories: {missing_primary}"

    # Check Secondary coverage
    missing_secondary = all_subcats - set(SECONDARY_ZH.keys())
    print(f"Missing Secondary count: {len(missing_secondary)}")
    if missing_secondary:
        print("Missing sample:", list(missing_secondary)[:20])
    assert not missing_secondary, f"Missing Secondary categories: {len(missing_secondary)} items"

    # Build zh.json
    zh_data = {
        "altium": ALTIUM_ZH,
        "primary": PRIMARY_ZH,
        "secondary": SECONDARY_ZH,
    }

    # Build en.json
    en_data = {
        "altium": ALTIUM_EN,
        "primary": {k: k for k in PRIMARY_ZH},
        "secondary": {k: k for k in SECONDARY_ZH},
    }

    zh_file = CATEGORIES_DIR / "zh.json"
    en_file = CATEGORIES_DIR / "en.json"

    with open(zh_file, "w", encoding="utf-8") as f:
        json.dump(zh_data, f, ensure_ascii=False, indent=2)
    print(f"Written: {zh_file}")

    with open(en_file, "w", encoding="utf-8") as f:
        json.dump(en_data, f, ensure_ascii=False, indent=2)
    print(f"Written: {en_file}")
    print("All categories and subcategories generated with 100% coverage!")

if __name__ == "__main__":
    main()
